use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn collect(dir: &Path, base: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = match fs::read_dir(dir) {
        Ok(rd) => rd.filter_map(|e| e.ok()).collect(),
        Err(_) => return,
    };
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect(&path, base, out);
        } else {
            let rel = path
                .strip_prefix(base)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.push((rel, path));
        }
    }
}

fn escape(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "\\\\").replace('"', "\\\"")
}

fn main() {
    println!("cargo:rerun-if-changed=assets");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=app.manifest");
    println!("cargo:rerun-if-changed=assets/icon.ico");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    // ---- embedded engine files -------------------------------------------------
    let assets_root = manifest_dir.join("assets").join("engine");
    let mut files = Vec::new();
    collect(&assets_root, &assets_root, &mut files);

    let mut code = String::new();
    code.push_str("// Generated by build.rs\n");
    code.push_str("pub static ENGINE_FILES: &[(&str, &[u8])] = &[\n");
    let mut total: u64 = 0;
    for (rel, path) in &files {
        total += fs::metadata(path).map(|m| m.len()).unwrap_or(0);
        code.push_str(&format!(
            "    ({:?}, include_bytes!(\"{}\")),\n",
            rel,
            escape(path)
        ));
    }
    code.push_str("];\n");
    code.push_str(&format!(
        "pub const ENGINE_FILE_COUNT: usize = {};\npub const ENGINE_TOTAL_BYTES: u64 = {};\n",
        files.len(),
        total
    ));

    // ---- embedded presets -------------------------------------------------------
    let presets_root = manifest_dir.join("assets").join("presets");
    let mut presets: Vec<(String, PathBuf)> = fs::read_dir(&presets_root)
        .map(|rd| {
            rd.filter_map(|e| e.ok())
                .filter(|e| {
                    let name = e.file_name().to_string_lossy().to_string();
                    name.starts_with("general") && name.ends_with(".bat")
                })
                .map(|e| (e.file_name().to_string_lossy().to_string(), e.path()))
                .collect()
        })
        .unwrap_or_default();
    presets.sort_by(|a, b| a.0.to_lowercase().cmp(&b.0.to_lowercase()));
    code.push_str("pub static PRESET_FILES: &[(&str, &[u8])] = &[\n");
    for (name, path) in &presets {
        code.push_str(&format!(
            "    ({:?}, include_bytes!(\"{}\")),\n",
            name,
            escape(path)
        ));
    }
    code.push_str("];\n");

    // Stamp changes when the binary assets change; used to refresh extracted engine.
    let mut hash: u64 = 1469598103934665603;
    for (rel, _) in &files {
        for b in rel.as_bytes() {
            hash ^= *b as u64;
            hash = hash.wrapping_mul(1099511628211);
        }
    }
    hash ^= total;
    hash = hash.wrapping_mul(1099511628211);
    code.push_str(&format!("pub const ENGINE_STAMP: &str = \"{:016x}\";\n", hash));

    fs::write(out_dir.join("embedded_assets.rs"), code).unwrap();

    // ---- windows resources ------------------------------------------------------
    let icon = manifest_dir.join("assets").join("icon.ico");
    if icon.exists() {
        let mut res = winresource::WindowsResource::new();
        res.set_icon(icon.to_string_lossy().as_ref());
        res.set("ProductName", "Unkn0WnDPI");
        res.set("FileDescription", "Unkn0WnDPI — обход DPI (zapret)");
        res.set("CompanyName", "Unkn0WnDPI");
        res.set("LegalCopyright", "zapret: bol-van, Flowseal presets");
        res.set("FileVersion", "2.0.0.0");
        res.set("ProductVersion", "2.0.0.0");
        if let Err(e) = res.compile() {
            println!("cargo:warning=resource compile failed: {e}");
        }
    }
}
